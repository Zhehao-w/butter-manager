param(
    [switch]$SkipFrontendBuild,
    [switch]$PortableZip,
    [string]$ExpectedTag = '',
    [string]$OutputDirectory = '',
    [string]$CargoExecutable = 'cargo'
)
$ErrorActionPreference = 'Stop'
Set-StrictMode -Version Latest
$taskRoot = [IO.Path]::GetFullPath((Split-Path -Parent $PSScriptRoot))
$taskArtifacts = Join-Path $taskRoot 'artifacts'
$taskOutput = if ($OutputDirectory) { [IO.Path]::GetFullPath($OutputDirectory) } else { Join-Path $taskArtifacts 'windows' }
if (-not $taskOutput.StartsWith($taskArtifacts + [IO.Path]::DirectorySeparatorChar, [StringComparison]::OrdinalIgnoreCase)) {
    throw 'Release output must be a dedicated folder beneath this repository artifacts/.'
}
$taskTarget = Join-Path $taskRoot 'src-tauri/target/portable-release'
$taskBuiltExe = [IO.Path]::GetFullPath((Join-Path $taskTarget 'x86_64-pc-windows-msvc/release/butter-manager.exe'))
$taskOutputExe = Join-Path $taskOutput 'butter-manager.exe'
foreach ($taskDirectory in @($taskOutput, $taskTarget)) {
    $taskAncestor = [IO.DirectoryInfo]::new($taskDirectory)
    while ($null -ne $taskAncestor) {
        if ((Test-Path -LiteralPath $taskAncestor.FullName) -and ((Get-Item -LiteralPath $taskAncestor.FullName).Attributes -band [IO.FileAttributes]::ReparsePoint)) { throw 'Build/output directories cannot contain links or junctions.' }
        if ($taskAncestor.FullName -eq $taskRoot) { break }
        $taskAncestor = $taskAncestor.Parent
    }
}
# This script never closes the app, touches its data, or overwrites an in-use executable.
foreach ($taskProcess in @(Get-CimInstance Win32_Process -Filter "Name = 'butter-manager.exe'")) {
    if ($taskProcess.ExecutablePath -and @($taskBuiltExe, $taskOutputExe) -contains [IO.Path]::GetFullPath($taskProcess.ExecutablePath)) {
        throw 'The build/output executable is running. Close that manager before building.'
    }
}
New-Item -ItemType Directory -Path $taskOutput -Force | Out-Null
function Clear-ReleaseOutput {
    # Only our exact outputs, in an explicitly bounded build directory; never remove data/.
    foreach ($taskFile in @(Get-ChildItem -LiteralPath $taskOutput -File)) {
        if ($taskFile.Name -eq 'butter-manager.exe' -or $taskFile.Name -eq 'SHA256SUMS.txt' -or $taskFile.Name -like 'butter-manager-v*-windows-x64-portable.zip*') {
            Remove-Item -LiteralPath $taskFile.FullName -Force
        }
    }
}
Clear-ReleaseOutput
try {
    $taskPackage = Get-Content -LiteralPath (Join-Path $taskRoot 'package.json') -Raw | ConvertFrom-Json
    $taskTauri = Get-Content -LiteralPath (Join-Path $taskRoot 'src-tauri/tauri.conf.json') -Raw | ConvertFrom-Json
    $taskCargo = Get-Content -LiteralPath (Join-Path $taskRoot 'src-tauri/Cargo.toml') -Raw
    $taskPackageSection = [regex]::Match($taskCargo, '(?ms)^\[package\]\s*(.*?)(?=^\[|\z)').Groups[1].Value
    $taskCargoVersion = [regex]::Match($taskPackageSection, '(?m)^version\s*=\s*"([^"]+)"').Groups[1].Value
    $taskVersion = $taskPackage.version
    if ($taskVersion -notmatch '^\d+\.\d+\.\d+(?:-[0-9A-Za-z.-]+)?(?:\+[0-9A-Za-z.-]+)?$' -or $taskVersion -ne $taskTauri.version -or $taskVersion -ne $taskCargoVersion) {
        throw 'package.json, Cargo.toml and tauri.conf.json must have the same valid version.'
    }
    if ($ExpectedTag -and $ExpectedTag -cne "v$taskVersion") { throw "Release tag must be v$taskVersion; versions are never changed automatically." }
    Push-Location $taskRoot
    try {
        if (-not $SkipFrontendBuild) {
            & pnpm.cmd build
            if ($LASTEXITCODE -ne 0) { throw 'Production frontend build failed.' }
        }
        if (-not (Test-Path -LiteralPath (Join-Path $taskRoot 'dist/index.html') -PathType Leaf)) { throw 'Missing production frontend resources.' }
        if (Test-Path -LiteralPath $taskBuiltExe) { Remove-Item -LiteralPath $taskBuiltExe -Force }
        & $CargoExecutable build --locked --manifest-path src-tauri/Cargo.toml --bin butter-manager --release --target x86_64-pc-windows-msvc --target-dir $taskTarget --features tauri/custom-protocol
        if ($LASTEXITCODE -ne 0) { throw 'Windows Release build failed.' }
    } finally { Pop-Location }
    if (-not (Test-Path -LiteralPath $taskBuiltExe -PathType Leaf) -or (Get-Item -LiteralPath $taskBuiltExe).Length -eq 0) { throw 'No executable was generated by this build.' }
    $taskExeVersion = (Get-Item -LiteralPath $taskBuiltExe).VersionInfo.ProductVersion
    if ($taskExeVersion -ne $taskVersion) { throw "Executable version mismatch: $taskExeVersion" }
    Copy-Item -LiteralPath $taskBuiltExe -Destination $taskOutputExe
    if ($PortableZip) {
        $taskZip = Join-Path $taskOutput "butter-manager-v$taskVersion-windows-x64-portable.zip"
        Add-Type -AssemblyName System.IO.Compression.FileSystem
        $taskArchive = [IO.Compression.ZipFile]::Open($taskZip + '.tmp', [IO.Compression.ZipArchiveMode]::Create)
        try { [IO.Compression.ZipFileExtensions]::CreateEntryFromFile($taskArchive, $taskOutputExe, 'butter-manager/butter-manager.exe', [IO.Compression.CompressionLevel]::Optimal) | Out-Null }
        finally { $taskArchive.Dispose() }
        Move-Item -LiteralPath ($taskZip + '.tmp') -Destination $taskZip
        $taskArchive = [IO.Compression.ZipFile]::OpenRead($taskZip)
        try {
            if ($taskArchive.Entries.Count -ne 1 -or $taskArchive.Entries[0].FullName -cne 'butter-manager/butter-manager.exe' -or $taskArchive.Entries[0].Length -ne (Get-Item -LiteralPath $taskOutputExe).Length) { throw 'Unexpected Portable ZIP contents.' }
        } finally { $taskArchive.Dispose() }
        # The standalone EXE remains a CI artifact; only the ZIP is distributed in Releases.
        $taskChecksums = '{0}  {1}' -f (Get-FileHash -LiteralPath $taskZip -Algorithm SHA256).Hash.ToLowerInvariant(), (Split-Path -Leaf $taskZip)
        Set-Content -LiteralPath (Join-Path $taskOutput 'SHA256SUMS.txt') -Value $taskChecksums -Encoding ascii
        Write-Output "Portable ZIP and ZIP checksum ready: $taskOutput"
    }
    Write-Output "Windows EXE v$taskVersion ready: $taskOutputExe"
} catch {
    Clear-ReleaseOutput
    throw
}
